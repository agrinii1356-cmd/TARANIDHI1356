function fold(s: string) {
  return s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9\u0900-\u097f]+/g, "");
}

export function searchCities(query: string, limit = 12): City[] {
  const q = query.trim();
  if (!q) return POPULAR_CITIES.slice(0, limit);
  const n = fold(q);
  if (!n) return POPULAR_CITIES.slice(0, limit);
  const ranked = CITIES.map((c) => {
    const name = fold(c.name);
    const region = fold(c.region);
    const aliases = (c.aliases ?? []).map(fold);
    let score = 0;
    if (name === n || aliases.includes(n)) score = 100;
    else if (name.startsWith(n) || aliases.some((a) => a.startsWith(n))) score = 90;
    else if (name.includes(n) || aliases.some((a) => a.includes(n))) score = 70;
    else if (region.startsWith(n) || region.includes(n)) score = 25;
    if (score > 0 && c.region.endsWith("India")) score += 4;
    return { c, score };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || a.c.name.localeCompare(b.c.name));
  return ranked.slice(0, limit).map((x) => x.c);
}

