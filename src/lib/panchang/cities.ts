export type City = {
  name: string;
  region: string;
  lat: number;
  lon: number;
  tz: number;
  aliases?: string[];
};

export type Place = Pick<City, "name" | "region" | "lat" | "lon" | "tz">;

function inCity(
  name: string,
  region: string,
  lat: number,
  lon: number,
  aliases?: string,
): City {
  return {
    name,
    region: `${region}, India`,
    lat,
    lon,
    tz: 5.5,
    aliases: aliases ? aliases.split("|") : undefined,
  };
}

function world(
  name: string,
  region: string,
  lat: number,
  lon: number,
  tz: number,
  aliases?: string,
): City {
  return {
    name,
    region,
    lat,
    lon,
    tz,
    aliases: aliases ? aliases.split("|") : undefined,
  };
}

