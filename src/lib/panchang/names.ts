export function localName(name: string, lang: Lang): string {
  if (lang !== "hi") return name;
  if (name.includes(" · ")) {
    return name
      .split(" · ")
      .map((part) => localName(part, lang))
      .join(" · ");
  }
  return HI[name] ?? name;
}

